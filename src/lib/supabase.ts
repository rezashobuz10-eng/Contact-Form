import { createClient, SupabaseClient } from '@supabase/supabase-js';

const STORAGE_KEY_URL = 'app_supabase_url';
const STORAGE_KEY_ANON = 'app_supabase_anon_key';

export function getStoredSupabaseConfig(): { url: string; anonKey: string } {
  const envUrl = (import.meta.env.VITE_SUPABASE_URL || '').trim();
  const envAnon = (import.meta.env.VITE_SUPABASE_ANON_KEY || '').trim();

  const storedUrl = (typeof window !== 'undefined' ? localStorage.getItem(STORAGE_KEY_URL) : null) || '';
  const storedAnon = (typeof window !== 'undefined' ? localStorage.getItem(STORAGE_KEY_ANON) : null) || '';

  // Use stored if present and valid, otherwise fallback to env if not placeholder
  const isEnvPlaceholder = !envUrl || envUrl.includes('your-project.supabase.co');
  const url = storedUrl || (!isEnvPlaceholder ? envUrl : '');
  const anonKey = storedAnon || (!isEnvPlaceholder ? envAnon : '');

  return { url, anonKey };
}

let cachedClient: SupabaseClient | null = null;
let lastUsedUrl = '';
let lastUsedAnon = '';

export function getSupabaseClient(): SupabaseClient | null {
  const { url, anonKey } = getStoredSupabaseConfig();

  if (!url || !anonKey) {
    return null;
  }

  if (cachedClient && lastUsedUrl === url && lastUsedAnon === anonKey) {
    return cachedClient;
  }

  try {
    cachedClient = createClient(url, anonKey, {
      auth: {
        persistSession: false,
      },
    });
    lastUsedUrl = url;
    lastUsedAnon = anonKey;
    return cachedClient;
  } catch (err) {
    console.error('Failed to initialize Supabase client:', err);
    return null;
  }
}

export function saveSupabaseConfig(url: string, anonKey: string): void {
  if (typeof window !== 'undefined') {
    localStorage.setItem(STORAGE_KEY_URL, url.trim());
    localStorage.setItem(STORAGE_KEY_ANON, anonKey.trim());
    cachedClient = null; // reset cache
  }
}

export function clearSupabaseConfig(): void {
  if (typeof window !== 'undefined') {
    localStorage.removeItem(STORAGE_KEY_URL);
    localStorage.removeItem(STORAGE_KEY_ANON);
    cachedClient = null;
  }
}

export interface ContactMessagePayload {
  name: string;
  email: string;
  message: string;
  createdAt?: string;
}

export async function insertMessageToSupabase(payload: ContactMessagePayload): Promise<{
  success: boolean;
  error?: string;
  data?: any;
}> {
  const client = getSupabaseClient();
  if (!client) {
    return {
      success: false,
      error: 'Supabase credentials are not configured yet.',
    };
  }

  try {
    // Attempt insert into 'contact_messages'
    const record = {
      name: payload.name,
      email: payload.email,
      message: payload.message,
      created_at: payload.createdAt || new Date().toISOString(),
    };

    const { data, error } = await client
      .from('contact_messages')
      .insert([record])
      .select();

    if (error) {
      // Fallback try 'messages' table if user named it 'messages'
      if (error.code === '42P01' || error.message.includes('relation "contact_messages" does not exist')) {
        const fallbackRes = await client.from('messages').insert([record]).select();
        if (fallbackRes.error) {
          return { success: false, error: fallbackRes.error.message };
        }
        return { success: true, data: fallbackRes.data };
      }
      return { success: false, error: error.message };
    }

    return { success: true, data };
  } catch (err: any) {
    return {
      success: false,
      error: err?.message || 'Network error connecting to Supabase.',
    };
  }
}

export async function testSupabaseConnection(url: string, anonKey: string): Promise<{
  success: boolean;
  message: string;
}> {
  try {
    const testClient = createClient(url.trim(), anonKey.trim());
    // Quick probe query to check validity of credentials
    const { error } = await testClient.from('contact_messages').select('id').limit(1);

    if (error) {
      if (error.code === '42P01' || error.message?.includes('does not exist')) {
        return {
          success: true,
          message: 'Connected to Supabase! (Note: "contact_messages" table is not created yet - see SQL script below)',
        };
      }
      return {
        success: false,
        message: error.message,
      };
    }

    return {
      success: true,
      message: 'Connection successful! Database table "contact_messages" is ready.',
    };
  } catch (err: any) {
    return {
      success: false,
      message: err?.message || 'Failed to connect to Supabase URL.',
    };
  }
}

export const SUPABASE_SQL_SETUP = `-- Run this in your Supabase SQL Editor:
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  message text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable Row Level Security (RLS)
alter table public.contact_messages enable row level security;

-- Allow anonymous or public visitors to insert contact form messages
create policy "Allow public form submissions" on public.contact_messages
  for insert with check (true);

-- Allow reading messages
create policy "Allow reading messages" on public.contact_messages
  for select using (true);
`;
